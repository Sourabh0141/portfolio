/**
 * Compiles Munshi's knowledge base from the same files the portfolio page is built from, plus
 * knowledge/facts.md, and writes it as a module the Worker bundles.
 *
 *   npm run knowledge -w worker
 *
 * The output is generated on every dev, test and deploy and is not committed, so it can never
 * disagree with the site content at the same commit.
 */
import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { about, education, focusAreas, profile, skills, socials } from '../../src/data/site.ts';
import { SITE_URL } from '../../src/site.config.ts';
import { checkKnowledge, renderKnowledge } from './lib/render-knowledge.ts';
import type { KnowledgeExperience, KnowledgeProject } from './lib/render-knowledge.ts';

const workerDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(workerDir, '..', 'src', 'content');
const outputFile = join(workerDir, 'src', 'generated', 'knowledge.ts');

/** Astro has already validated these files against src/content.config.ts during `astro check`. */
async function readCollection<T>(name: string): Promise<T[]> {
  const dir = join(contentDir, name);
  const files = (await readdir(dir)).filter((file) => file.endsWith('.yaml')).sort();
  return Promise.all(
    files.map(async (file) => parse(await readFile(join(dir, file), 'utf8')) as T),
  );
}

const [projects, experience, facts] = await Promise.all([
  readCollection<KnowledgeProject>('projects'),
  readCollection<KnowledgeExperience>('experience'),
  readFile(join(workerDir, 'knowledge', 'facts.md'), 'utf8'),
]);

const knowledge = renderKnowledge({
  siteUrl: SITE_URL,
  profile,
  socials,
  about,
  focusAreas,
  skills,
  education,
  projects,
  experience,
  facts,
});

// Check for unfinished notes (TODO/TBD/FIXME) or oversize knowledge.
const problems = checkKnowledge(knowledge, []);
if (problems.length > 0) {
  console.error(
    `Knowledge build failed:\n${problems.map((problem) => `  - ${problem}`).join('\n')}`,
  );
  process.exit(1);
}

const version = createHash('sha256').update(knowledge).digest('hex').slice(0, 12);
const source = `// Generated by scripts/build-knowledge.ts. Do not edit.
export const KNOWLEDGE_VERSION = ${JSON.stringify(version)};
export const KNOWLEDGE = ${JSON.stringify(knowledge)};
`;

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(outputFile, source);
console.log(`Knowledge ${version}: ${knowledge.length} characters.`);
